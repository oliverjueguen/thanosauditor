"""Core tests: diff, noise filter, scoring and aggregation
(RF-12, RF-14, RF-15, RF-20). Expectations about the real bundle come from the
real Practice 1 (P1) data."""

from __future__ import annotations

from thanos.core import aggregate, artifact_diffs, score_for, validate_bundle
from thanos.core.bundles import ArtifactDiff
from thanos.core.noise import filter_names, is_autogenerated
from thanos.core.scoring import priority_for, severity_for


def _by_name(bundle):
    return {d.logical_name: d for d in artifact_diffs(bundle)}


# --- Schema (RF-15) ------------------------------------------------------ #

def test_validate_fixtures(real_bundle, synth_bundle):
    """RF-15: the real and synthetic bundles conform to the schema."""
    assert validate_bundle(real_bundle) == []
    assert validate_bundle(synth_bundle) == []


def test_numeric_target_build_from_p1(real_bundle):
    """RNF-06: the real bundle has a numeric target_build (YAML bug in P1);
    it is normalized to a string and a warning is issued without rejecting the bundle."""
    from thanos.core.bundles import lint_bundle, target_build

    assert isinstance(real_bundle["target_build"], float)
    # Derived from version_after (10.0.20348.5020), the build MSRC confirms.
    assert target_build(real_bundle) == "20348.5020"
    warnings = lint_bundle(real_bundle)
    assert len(warnings) == 1 and "unquoted YAML" in warnings[0]
    assert aggregate([real_bundle])[0]["target_build"] == "20348.5020"


import pytest  # noqa: E402

_OK = {"patch_cycle": "c", "target_build": "1", "kb_ids": [], "artifacts": []}


@pytest.mark.parametrize("value", [5, None, "x", [], 3.2, True])
def test_validate_rejects_non_objects(value):
    """RNF-06: any JSON value that is not an object is rejected without raising."""
    assert validate_bundle(value) == ["the bundle must be a JSON object"]


@pytest.mark.parametrize("patch, expected", [
    ({"artifacts": "abc"}, "'artifacts' must be a list"),
    ({"artifacts": [1]}, "artifact[0] is not an object"),
    ({"patch_cycle": 12345}, "'patch_cycle' must be a string"),
    ({"patch_cycle": "x" * 200}, "'patch_cycle' must be a string"),
    ({"kb_ids": "KB1"}, "'kb_ids' must be a list"),
    ({"target_build": None}, "'target_build' must be a string or a number"),
    ({"changes": "x"}, "'changes' must be a list of objects"),
    ({"artifacts": [{"logical_name": "a", "sha256_before": "x", "sha256_after": "y",
                     "summary_after": {"function_count": "lots"}}]}, "numeric counters"),
    ({"artifacts": [{"logical_name": "a", "sha256_before": "x", "sha256_after": "y",
                     "size_after": "1"}]}, "'size_after' must be a number"),
])
def test_validate_rejects_wrong_types(patch, expected):
    errors = validate_bundle({**_OK, **patch})
    assert any(expected in e for e in errors), errors


def test_validate_detects_missing_fields():
    errors = validate_bundle({"artifacts": [{"logical_name": "x.dll"}]})
    assert any("patch_cycle" in e for e in errors)
    assert any("sha256_before" in e for e in errors)


# --- Diff (RF-12, RF-14) -------------------------------------------------- #

def test_real_bundle_all_pairs_changed(real_bundle):
    """RF-12: in the real bundle, all 85 pairs have a different SHA-256."""
    diffs = artifact_diffs(real_bundle)
    assert len(diffs) == 85
    assert all(d.changed for d in diffs)


def test_real_bluetooth_has_no_code_diff(real_bundle):
    """RF-14: microsoft.bluetooth.service.dll changes its SHA but not its code."""
    bt = _by_name(real_bundle)["microsoft.bluetooth.service.dll"]
    assert bt.changed
    assert bt.fn_delta == 0 and bt.size_delta == 0
    assert not bt.has_code_diff


def test_identical_sha_not_changed():
    """RF-12: a pair with an identical SHA is considered unchanged."""
    same = ArtifactDiff(logical_name="x.dll", person="p", sha256_before="aaa", sha256_after="aaa")
    assert same.changed is False


# --- Ghidra noise filter (P1 roadmap improvement) ------------------------ #

def test_is_autogenerated():
    for name in ("Unwind@1000a570", "Catch@10018f9e", "FUN_1800a2b0", "LAB_00401000",
                 "thunk_FUN_10043c20", "thunk_EXT_FUN_064b13bd"):
        assert is_autogenerated(name), name
    for name in ("DelayLoad_WinHttpOpen", "ApiSetQueryApiSetPresence", "__allmul", "Unwind"):
        assert not is_autogenerated(name), name


def test_filter_names_counts_noise():
    real, dropped = filter_names(["Unwind@1000a570", "Catch@10018f9e", "DelayLoad_WinHttpOpen"])
    assert real == ["DelayLoad_WinHttpOpen"]
    assert dropped == 2


def test_real_noise_is_filtered(real_bundle):
    """In the real bundle, 260 of 324 names in the diff are Ghidra noise."""
    diffs = _by_name(real_bundle)
    assert sum(d.noise_filtered for d in diffs.values()) == 260
    # +6/-6 Catch@ due to address shifts: zero real changes.
    dt = diffs["windows.applicationmodel.datatransfer.dll"]
    assert dt.noise_filtered == 12
    assert dt.fn_changes == 0
    # clipboardserver: 200 noise names, 1 real change.
    cs = diffs["clipboardserver.dll"]
    assert cs.noise_filtered == 200
    assert cs.fn_removed == ["__allmul"]


def test_real_upnphost_new_delay_loads(real_bundle):
    """upnphost.dll gains delay-loaded network dependencies (WinHTTP)."""
    up = _by_name(real_bundle)["upnphost.dll"]
    assert len(up.delay_loads_added) == 24
    assert "DelayLoad_WinHttpOpen" in up.delay_loads_added


# --- Real bundle from the split run and cross-check ---------------------- #

def test_split_bundle(split_bundle):
    """RF-15: the real split bundle is valid and its 7 pairs changed."""
    assert validate_bundle(split_bundle) == []
    diffs = _by_name(split_bundle)
    assert len(diffs) == 7
    assert all(d.changed for d in diffs.values())


def test_playready_is_wow64_and_its_diff_is_noise(split_bundle):
    """playready.dll in the split run is the wow64 package; of its +8/-8 functions, 15
    are auto-generated names (FUN_, thunk_FUN_, thunk_EXT_FUN_) and the only named
    change is a removed C runtime helper (__break)."""
    pr = _by_name(split_bundle)["windows.media.protection.playready.dll"]
    assert pr.arch == "wow64"
    assert pr.noise_filtered == 15
    assert pr.fn_added == [] and pr.fn_removed == ["__break"]
    assert pr.fn_delta == -15            # the total count does change


def test_reconstruction_is_deterministic_across_runs(real_bundle, split_bundle):
    """RF-05/RF-12 with real data: two independent pipeline runs (split at 17:52 and
    full at 21:57 on 2026-05-07) rebuilt the same binaries with identical SHA-256
    hashes before and after the patch."""
    full = {a["logical_name"]: a for a in real_bundle["artifacts"]}
    common = [a for a in split_bundle["artifacts"] if a["logical_name"] in full]
    assert {a["logical_name"] for a in common} == {"diagnostic.dll", "wdsclient.dll"}
    for a in common:
        o = full[a["logical_name"]]
        assert a["sha256_before"] == o["sha256_before"]
        assert a["sha256_after"] == o["sha256_after"]
        assert a["summary_after"] == o["summary_after"]


# --- Scoring (RF-20) ------------------------------------------------------ #

def test_scoring_fallback_without_name_diff(synth_bundle):
    """Without a `changes` section the function count change is used (weight 2):
    synthetic configmanager2.dll (+120 functions) scores 120 x 2 = 240."""
    cm = _by_name(synth_bundle)["configmanager2.dll"]
    assert not cm.has_name_diff
    assert score_for(cm) == 240


def test_real_top_is_upnphost(real_bundle):
    scores = {name: score_for(d) for name, d in _by_name(real_bundle).items()}
    assert max(scores, key=scores.get) == "upnphost.dll"


def test_priority_bands():
    assert priority_for(264) == "P1"
    assert priority_for(100) == "P2"
    assert priority_for(30) == "P3"
    assert priority_for(0) == "P4"


def test_severity_exports_raise_level():
    """An export change raises the severity (attack surface)."""
    with_exports = ArtifactDiff(
        logical_name="x.dll", person="p", sha256_before="a", sha256_after="b", exp_delta=10
    )
    assert severity_for(with_exports) in ("high", "critical")


# --- Aggregation (RF-18/19/20) ------------------------------------------- #

def test_aggregate_real_and_synthetic(real_bundle, synth_bundle):
    """RF-20: two people in the same cycle are aggregated with KPIs and ranking."""
    cycles = aggregate([real_bundle, synth_bundle])
    assert len(cycles) == 1
    cycle = cycles[0]
    assert cycle["kpis"]["bundles"] == 2
    assert cycle["kpis"]["artifacts"] == 85 + 3
    assert cycle["kpis"]["noise_filtered"] == 260
    assert set(cycle["kb_ids"]) == {"KB5078766", "KB5082142"}
    # Sorted by descending score.
    scores = [a["score"] for a in cycle["artifacts"]]
    assert scores == sorted(scores, reverse=True)
