"""Packages each team member's work into a ZIP (RF-08, Phase 5).

``thanos-<person>.zip`` contains what the executor needs on their machine:

- the files from ``executor/`` (bootstrap.ps1, run_diff.py, CLAUDE.md, README.md,
  config.example.yaml);
- a PRECONFIGURED ``config.yaml`` with their id, cycle, build (quoted: in P1 an
  unquoted build was parsed as a float and lost the trailing zero) and KBs;
- ``assignment.json`` with the binaries assigned to them (output of RF-07);
- the ``thanos/`` package (imported by run_diff.py).

The DLLs for ``input/before`` and ``input/after`` are added on the coordinator from
``reconstructed/`` (Windows); here only the folder structure is created.
"""

from __future__ import annotations

import json
import zipfile
from pathlib import Path
from typing import Any

import yaml

from ..config import project_root

_EXECUTOR_FILES = ("bootstrap.ps1", "run_diff.py", "config.example.yaml", "CLAUDE.md", "README.md")


def executor_config(person: str, cycle: dict[str, Any]) -> str:
    """config.yaml content for one person (target_build always as text)."""
    data = {
        "executor_id": person,
        "patch_cycle": cycle["patch_cycle"],
        "target_product": cycle.get("target_product", "Windows Server 2022"),
        "target_build": str(cycle["target_build"]),
        "kb_ids": list(cycle.get("kb_ids", [])),
        "cve_ids": list(cycle.get("cve_ids", [])),
        "ghidra_support_dir": "C:\\path\\to\\ghidra\\support",
        "input_dir": "input",
        "output_dir": "output",
    }
    header = "# Generated by the coordinator (RF-08). Only ghidra_support_dir needs editing.\n"
    return header + yaml.safe_dump(data, allow_unicode=True, sort_keys=False)


def build_zip(person: str, assignment: list[dict[str, Any]], cycle: dict[str, Any], dest_dir: Path) -> Path:
    """Create staging/zips/thanos-<person>.zip and return its path."""
    root = project_root()
    dest_dir.mkdir(parents=True, exist_ok=True)
    zip_path = dest_dir / f"thanos-{person}.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for name in _EXECUTOR_FILES:
            src = root / "executor" / name
            if src.exists():
                zf.write(src, name)
        zf.writestr("config.yaml", executor_config(person, cycle))
        zf.writestr("assignment.json", json.dumps(assignment, ensure_ascii=False, indent=2))
        zf.writestr("input/before/.keep", "")
        zf.writestr("input/after/.keep", "")
        for src in sorted((root / "thanos").rglob("*")):
            if src.is_file() and "__pycache__" not in src.parts and src.suffix != ".pyc":
                zf.write(src, src.relative_to(root).as_posix())
    return zip_path
