"""Thanos Auditor CLI.

Examples::

    # Heuristic triage (no LLM, always works)
    python -m thanos.auditor.cli analyze "fixtures/bundles/*.bundle.json" -o output/report.json

    # Claude session (once) and triage with Claude
    python -m thanos.auditor.cli login
    python -m thanos.auditor.cli status
    python -m thanos.auditor.cli analyze "fixtures/bundles/*.bundle.json" --backend claude -o output/report.json

Exit codes: 0 success, 2 bad input, 3 Claude failure with --no-fallback.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess  # nosec B404 - only to launch the Claude CLI with fixed arguments
import sys
from pathlib import Path
from typing import Any

from ..cliutil import CliError, expand_files, fail, load_json_file, utf8_stdout
from ..config import load_env
from ..core.bundles import lint_bundle, validate_bundle
from ..log import setup_logging
from .backends import AnalystError, analyze


def claude_cli() -> Path | None:
    """Claude Code CLI: the one bundled with the Agent SDK or, failing that, the one on PATH."""
    try:
        import claude_agent_sdk

        exe = "claude.exe" if os.name == "nt" else "claude"
        bundled = Path(claude_agent_sdk.__file__).parent / "_bundled" / exe
        if bundled.exists():
            return bundled
    except ImportError:
        pass
    found = shutil.which("claude")
    return Path(found) if found else None


def _run_claude(args: list[str]) -> int:
    cli = claude_cli()
    if cli is None:
        raise CliError(
            "Claude CLI not found: install the auditor extra with "
            "pip install -e \".[auditor]\" (it ships the bundled CLI)"
        )
    return subprocess.call([str(cli), *args])  # nosec B603 - fixed list, no shell


def _load_bundles(patterns: list[str]) -> list[dict[str, Any]]:
    bundles, warned = [], set()
    for path in expand_files(patterns):
        bundle = load_json_file(path)
        errors = validate_bundle(bundle)
        if errors:
            raise CliError(f"'{path}' is not a valid bundle: {errors[0]}")
        for warning in lint_bundle(bundle):
            if warning not in warned:
                print(f"warning: {path.name}: {warning}", file=sys.stderr)
                warned.add(warning)
        bundles.append(bundle)
    return bundles


def _print_summary(report: dict[str, Any]) -> None:
    for cycle in report.get("cycles", [report]):
        print(f"\n== {cycle.get('patch_cycle', '?')} · {cycle.get('target_build', '')} "
              f"(generated by: {report.get('generated_by')}) ==")
        print(cycle.get("summary", ""))
        print(f"\n{'PRIO':<5}{'SEV':<10}{'CONF':<8}{'BINARY':<46}REASON")
        for t in cycle.get("review_targets", [])[:10]:
            reason = t.get("rationale", "").replace("\n", " ")
            print(f"{t['priority']:<5}{t['severity']:<10}{t['confidence']:<8}"
                  f"{t['logical_name'][:44]:<46}{reason[:90]}")
        rest = len(cycle.get("review_targets", [])) - 10
        if rest > 0:
            print(f"… and {rest} more binaries (use -o or --json for the full report)")


def main(argv: list[str] | None = None) -> int:
    utf8_stdout()
    load_env()
    setup_logging()
    parser = argparse.ArgumentParser(prog="thanos-auditor", description="Thanos Auditor: patch triage.")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("analyze", help="Analyze bundles and generate the triage report.")
    p.add_argument("bundles", nargs="+", help="bundle.json files (wildcards allowed).")
    p.add_argument("--backend", choices=["heuristic", "claude"], default="heuristic")
    p.add_argument("--model", help="Model for the claude backend (default THANOS_AUDITOR_MODEL).")
    p.add_argument("--no-fallback", action="store_true",
                   help="With --backend claude, fail (rc 3) instead of falling back to the heuristic.")
    p.add_argument("-o", "--output", help="Where to save the full JSON report.")
    p.add_argument("--json", action="store_true", help="Print the full JSON report.")

    sub.add_parser("login", help="Log in with your Claude account (subscription).")
    sub.add_parser("status", help="Show the Claude session the auditor will use.")

    args = parser.parse_args(argv)
    try:
        if args.cmd == "login":
            return _run_claude(["auth", "login", "--claudeai"])
        if args.cmd == "status":
            if os.environ.get("ANTHROPIC_API_KEY"):
                print("warning: ANTHROPIC_API_KEY is set and takes precedence over the "
                      "subscription (billed per token).", file=sys.stderr)
            return _run_claude(["auth", "status", "--text"])
        return _analyze(args)
    except CliError as exc:
        return fail(str(exc))


def _analyze(args: argparse.Namespace) -> int:
    bundles = _load_bundles(args.bundles)
    try:
        report = analyze(bundles, backend=args.backend, model=args.model,
                         fallback=not args.no_fallback)
    except AnalystError as exc:
        hint = "; log in with: python -m thanos.auditor.cli login" if "logged in" in str(exc).lower() else ""
        return fail(f"Claude could not complete the analysis: {exc}{hint}", code=3)

    if report.get("warning"):
        print(f"warning: {report['warning']}", file=sys.stderr)
    text = json.dumps(report, ensure_ascii=False, indent=2)
    if args.output:
        out = Path(args.output)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        print(f"Report saved to {out} (generated by: {report.get('generated_by')}).")
    if args.json:
        print(text)
    else:
        _print_summary(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
